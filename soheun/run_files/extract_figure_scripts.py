#!/usr/bin/env python3
"""Materialise standalone figure scripts from the draft notebooks.

Each notebook cell that contributes to a manuscript figure is copied out verbatim
into run_files/figure_scripts/<key>.py. Only three things change:

  * cell 0 is dropped everywhere (it is the cwd assert + chdir boilerplate that the
    generated header replaces),
  * IPython magics are blanked and `display` becomes a no-op,
  * listed rewrites narrow sweeps to what the manuscript actually shows.

Re-run this after editing a notebook to refresh the scripts.
"""

