MAGIC = re.compile(r"^\s*[%!]")


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "__init__.py").write_text("")
    for spec in SPECS:
        notebook = nbformat.read(REPO / spec["notebook"], as_version=4)
        chunks = [
            HEADER.format(
                notebook=spec["notebook"],
                cells=spec["cells"],
                figures=", ".join(spec["figures"]),
                note=spec.get("note", ""),
            )
        ]
        for index in spec["cells"]:
            cell = notebook.cells[index]
            if cell.cell_type != "code":
                continue
            source = "\n".join(
                "" if MAGIC.match(line) else line for line in cell.source.splitlines()
            )
            for cell_index, pattern, replacement in spec.get("rewrites", []):
                if cell_index == index:
                    source, n = re.subn(pattern, replacement, source, flags=re.MULTILINE)
                    if n == 0:
                        raise SystemExit(
                            f"{spec['key']}: rewrite for cell {index} matched nothing: {pattern!r}"
                        )
            chunks.append(f"\n# ---------------- cell {index} ----------------\n{source}\n")
        chunks.append(
            "\nprint('done: " + spec["key"] + "', flush=True)\n"
        )
        path = OUT_DIR / f"{spec['key']}.py"
        path.write_text("\n".join(chunks))
        lines = len(path.read_text().splitlines())
        print(f"wrote {path.relative_to(REPO)}  ({lines} lines, {len(spec['figures'])} figure(s))")


if __name__ == "__main__":
    main()
